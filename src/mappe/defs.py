# Definizione a dati delle due mappe. Colori BES: c=pesca(centro) d=celeste(date/sequenze) k=paglierino(parole chiave) e=menta(esempi/opere) q=lilla(conseguenze)
def B(id,x,y,w,cls,html,**k): return dict(id=id,x=x,y=y,w=w,cls=cls,html=html,**k)
def I(id,x,y,w,img,cap,**k): return dict(id=id,x=x,y=y,w=w,cls='e',html=cap,img=img,**k)
def U(*items): return '<ul>'+''.join(f'<li>{i}</li>' for i in items)+'</ul>'
def S(cue,boxes,arrows=(),hl=None,cam=None):
    return dict(cue=cue,boxes=list(boxes),arrows=[tuple(a) for a in arrows],hl=hl or [],cam=cam or [])
def A(f,t,l=None,o=None): return dict(f=f,t=t,l=l,o=o)

